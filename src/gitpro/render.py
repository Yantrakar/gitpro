"""Pure text rendering: config objects in, file contents out. No I/O."""
from __future__ import annotations

import re
import shlex
from pathlib import Path
from typing import Callable

from .config import Default, Identity, check, signs

TOOL = "gitpro"
# Also recognise what earlier versions wrote (git-identities, git_identities.py), so existing setups migrate.
_TOOLS = r"(?:gitpro|git-identities|git_identities\.py)"

MARKER = f"# Generated by {TOOL}"
HEADER = f"{MARKER} -- edit the TOML config and re-run; do not edit this file."
MANIFEST = "# managed: "
BLOCK_BEGIN = f"# BEGIN {TOOL}"
BLOCK_END = f"# END {TOOL}"

SECTION_RE = re.compile(r"^[A-Za-z0-9.-]+$")
KEY_RE = re.compile(r"^[A-Za-z][A-Za-z0-9-]*$")
_GENERATED_RE = re.compile(rf"# Generated by {_TOOLS}(?:\s|$)")
_BLOCK_RE = re.compile(rf"^# BEGIN {_TOOLS}[^\n]*\n.*?^# END {_TOOLS}[^\n]*(?:\n|\Z)", re.M | re.S)
_MARK_RE = re.compile(rf"^# (BEGIN|END) {_TOOLS}", re.M)

Expand = Callable[[str], Path]


# ---------------------------------------------------------------- gitconfig syntax

def gval(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def section(name: str, sub: str | None = None) -> str:
    return f"[{name}]" if sub is None else f"[{name} {gval(sub)}]"


def _kv_lines(body: dict, where: str) -> list[str]:
    out = []
    for k, v in body.items():
        check(KEY_RE.match(k), f"{where}: bad git key {k!r}")
        for item in v if isinstance(v, list) else [v]:
            check(not isinstance(item, (dict, list)), f"{where}.{k}: nested too deep")
            out.append(f"\t{k} = {gval(item)}")
    return out


def git_lines(sections: dict, where: str) -> list[str]:
    """{section: {key: val, subsection: {key: val}}} -> gitconfig lines."""
    out = []
    for sec, body in sections.items():
        check(isinstance(body, dict) and SECTION_RE.match(sec), f"{where}: bad git section {sec!r}")
        flat = {k: v for k, v in body.items() if not isinstance(v, dict)}
        if flat:
            out += [section(sec), *_kv_lines(flat, f"{where}.{sec}")]
        for sub, sbody in body.items():
            if isinstance(sbody, dict):
                out += [section(sec, sub), *_kv_lines(sbody, f"{where}.{sec}.{sub}")]
    return out


def merge(a: dict, b: dict) -> dict:
    out = dict(a)
    for k, v in b.items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


# ---------------------------------------------------------------- helpers

def pub_path(key: Path) -> Path:
    return key.with_name(key.name + ".pub")


def _shell_path(p: str) -> str:
    return "~/" + shlex.quote(p[2:]) if p.startswith("~/") else shlex.quote(p)


def _owner_prefixes(i: Identity) -> list[str]:
    return [o.strip("/") + "/" for o in i.owners] or [""]


def url_patterns(i: Identity) -> list[str]:
    pats = []
    for o in _owner_prefixes(i):
        for h in [i.host] + ([i.ssh_alias] if i.ssh_alias else []):
            pats += [f"{i.ssh_user}@{h}:{o}**", f"ssh://{i.ssh_user}@{h}/{o}**"]
        if i.ssh_port:
            pats.append(f"ssh://{i.ssh_user}@{i.host}:{i.ssh_port}/{o}**")
        pats.append(f"https://{i.host}/{o}**")
    return list(dict.fromkeys(pats))


def _sign_cfg(key: Path) -> dict:
    return {"gpg": {"format": "ssh"}, "user": {"signingkey": str(pub_path(key))},
            "commit": {"gpgsign": True}, "tag": {"gpgsign": True}}


# ---------------------------------------------------------------- files

def managed_gitconfig(d: Default, ids: list[Identity], expand: Expand,
                      signers_file: str | None, manifest: list[str]) -> str:
    lines = [HEADER, *(MANIFEST + m for m in manifest), "# Later includeIf blocks win when several match.", ""]
    # Never fall back to a guessed user@hostname identity.
    base: dict = {"user": {"useConfigOnly": True}}
    if d.name:
        base["user"].update(name=d.name, email=d.email)
    if d.sign:
        base = merge(base, _sign_cfg(expand(d.ssh_key)))
    if signers_file:
        base = merge(base, {"gpg": {"ssh": {"allowedSignersFile": signers_file}}})
    lines += git_lines(merge(base, d.git), "default.git")
    for i in ids:
        lines += ["", f"# {i.id}: {i.host} {' '.join(i.owners) or '(all owners)'}"]
        for p in url_patterns(i):
            lines += [section("includeIf", f"hasconfig:remote.*.url:{p}"), f"\tpath = {gval(i.file)}"]
        if i.ssh_alias and i.rewrite:
            # Send this identity's URLs through the alias, whose ssh Host offers only its key.
            for o in _owner_prefixes(i):
                if "*" in o:
                    continue
                srcs = [f"{i.ssh_user}@{i.host}:{o}", f"ssh://{i.ssh_user}@{i.host}/{o}"]
                if i.rewrite_https:
                    srcs.append(f"https://{i.host}/{o}")
                lines.append(section("url", f"{i.ssh_user}@{i.ssh_alias}:{o}"))
                lines += [f"\tinsteadOf = {gval(s)}" for s in srcs]
    return "\n".join(lines) + "\n"


def identity_gitconfig(i: Identity, d: Default, expand: Expand) -> str:
    base: dict = {"user": {"name": i.name, "email": i.email}}
    if i.ssh_key:
        base["core"] = {"sshCommand": f"ssh -i {_shell_path(i.ssh_key)} -o IdentitiesOnly=yes"}
    if signs(i, d):
        base = merge(base, _sign_cfg(expand(i.ssh_key or d.ssh_key)))
    elif d.sign:
        base = merge(base, {"commit": {"gpgsign": False}, "tag": {"gpgsign": False}})
    return "\n".join([HEADER, *git_lines(merge(base, i.git), f"identity {i.id!r}.git")]) + "\n"


def _ssh_block(name: str, key: str, host: str | None = None, user: str | None = None,
               port: int | None = None) -> list[str]:
    lines = [f"Host {name}"]
    if host:
        lines.append(f"    HostName {host}")
    if user:
        lines.append(f"    User {user}")
    if port:
        lines.append(f"    Port {port}")
    return lines + [f"    IdentityFile {key}", "    IdentitiesOnly yes", ""]


def ssh_config(d: Default, ids: list[Identity]) -> str:
    lines = [HEADER, ""]
    for h in d.ssh_hosts:
        lines += _ssh_block(h, d.ssh_key)
    for i in ids:
        if i.ssh_alias:
            lines += _ssh_block(i.ssh_alias, i.ssh_key, i.host, i.ssh_user, i.ssh_port)
    return "\n".join(lines)


def allowed_signers(entries: list[tuple[str, str]]) -> str:
    return "\n".join([HEADER, *(f'{email} namespaces="git" {pub}' for email, pub in entries)]) + "\n"


# ---------------------------------------------------------------- generated files, marked blocks in user files

def is_generated(text: str) -> bool:
    return bool(_GENERATED_RE.match(text))


def has_block(text: str) -> bool:
    return bool(_MARK_RE.search(text))


def without_block(text: str) -> str:
    return _BLOCK_RE.sub("", text)


def _check_markers(text: str, where: str) -> None:
    # An orphaned marker would make without_block swallow the hand-written text between two blocks.
    marks = _MARK_RE.findall(text)
    check(marks == ["BEGIN", "END"] * (len(marks) // 2),
          f"{where}: unpaired '{BLOCK_BEGIN}' / '{BLOCK_END}' marker; fix it by hand")


def with_block(text: str, body: str, first: bool, where: str) -> str:
    """Exactly one marked block at the start or end of text; re-running is a no-op."""
    _check_markers(text, where)
    block = f"{BLOCK_BEGIN} -- keep {'first' if first else 'last'}\n{body}\n{BLOCK_END}\n"
    rest = without_block(text)
    if first:
        rest = rest.lstrip("\n")
        return block + ("\n" + rest if rest else "")
    rest = rest.rstrip("\n")
    return (rest + "\n\n" if rest else "") + block


def strip_block(text: str, where: str) -> str:
    """text without the marked block and the blank lines with_block added around it."""
    _check_markers(text, where)
    rest = without_block(text).strip("\n")
    return rest + "\n" if rest else ""


def manifest_of(text: str) -> list[str]:
    return [line[len(MANIFEST):] for line in text.splitlines() if line.startswith(MANIFEST)]
